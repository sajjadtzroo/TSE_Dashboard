def fetch_and_store_tickers(session) -> int:
    """
    Fetch top 30 listings from CoinMarketCap, map to tracked securities,
    and bulk-insert CryptoTicker rows.

    CMC provides USD + IRR quotes in a single call (no Wallex needed).
    Returns the number of ticker rows inserted.
    """
    fa_to_id, en_to_id = _get_crypto_security_map(session)

    listings = _cmc.fetch_listings(limit=200)
    if not listings:
        logger.warning("CMC returned no listings")
        return 0

    now = datetime.now(UTC)
    rows = []

    for coin in listings:
        symbol = coin.get("symbol", "")
        cmc_name = coin.get("name", symbol)
        security_id = _resolve_security_id(session, symbol, cmc_name, fa_to_id, en_to_id)
        if security_id is None:
            continue

        usd_quote = coin.get("quote", {}).get("USD", {})
        irr_quote = coin.get("quote", {}).get("IRR", {})

        last_price = usd_quote.get("price")
        if last_price is not None:
            last_price = Decimal(str(last_price))

        pct_24h = usd_quote.get("percent_change_24h")
        price_change_24h = None
        if last_price and pct_24h is not None:
            price_change_24h = last_price * Decimal(str(pct_24h)) / Decimal("100")

        volume_24h = usd_quote.get("volume_24h")
        market_cap = usd_quote.get("market_cap")

        # IRR price from CMC's built-in conversion
        price_toman = None
        irr_price = irr_quote.get("price")
        if irr_price is not None:
            price_toman = Decimal(str(irr_price))

        rows.append(
            {
                "security_id": security_id,
                "snapshot_time": now,
                "last_price": last_price,
                "price_change_24h": price_change_24h,
                "price_change_pct_24h": (
                    Decimal(str(pct_24h)) if pct_24h is not None else None
                ),
                "high_24h": None,  # CMC listings don't include 24h high/low
                "low_24h": None,
                "volume_24h": (
                    Decimal(str(volume_24h)) if volume_24h is not None else None
                ),
                "turnover_24h": (
                    Decimal(str(volume_24h)) if volume_24h is not None else None
                ),
                "best_bid": None,  # CMC doesn't provide bid/ask
                "best_ask": None,
                "market_cap_usd": (
                    Decimal(str(market_cap)) if market_cap is not None else None
                ),
                "price_toman": price_toman,
            }
        )

    if not rows:
        logger.warning("No matching crypto securities for CMC listings")
        return 0

    # Bulk insert
    session.execute(CryptoTicker.__table__.insert(), rows)
    session.flush()

    logger.info(f"Inserted {len(rows)} crypto ticker snapshots")

    # Publish live update via Redis pub/sub
    _publish_crypto_update(
        {
            "event": "crypto_ticker",
            "count": len(rows),
            "timestamp": now.isoformat(),
        }
    )

    return len(rows)


def generate_daily_ohlcv_from_tickers(session) -> int:
    """
    Generate daily OHLCV candles by aggregating CryptoTicker snapshots.
    For each tracked crypto, aggregate yesterday's ticker snapshots into:
      open  = first snapshot's last_price
      close = last snapshot's last_price
      high  = max(last_price)
      low   = min(last_price)
      volume = last snapshot's volume_24h (cumulative from CMC)

    Upserts via INSERT ... ON CONFLICT DO UPDATE.
    Returns the total number of rows upserted.
    """
    fa_to_id, en_to_id = _get_crypto_security_map(session)
    # Collect all unique security_ids
    all_sec_ids = set(fa_to_id.values()) | set(en_to_id.values())
    if not all_sec_ids:
        logger.warning("No crypto securities found; skipping OHLCV generation")
        return 0

    # Aggregate yesterday's ticker snapshots
    yesterday = date.today() - timedelta(days=1)
    day_start = datetime(yesterday.year, yesterday.month, yesterday.day, tzinfo=UTC)
    day_end = day_start + timedelta(days=1)

    interval = "1day"
    total_upserted = 0

    for security_id in all_sec_ids:
        # Get aggregated stats for yesterday
        agg_stmt = select(
            func.min(CryptoTicker.last_price).label("low"),
            func.max(CryptoTicker.last_price).label("high"),
            func.count(CryptoTicker.id).label("cnt"),
        ).where(
            CryptoTicker.security_id == security_id,
            CryptoTicker.snapshot_time >= day_start,
            CryptoTicker.snapshot_time < day_end,
            CryptoTicker.last_price.isnot(None),
        )
        agg = session.execute(agg_stmt).first()

        if not agg or agg.cnt == 0:
            continue

        # Get first snapshot (open price)
        first_stmt = (
            select(CryptoTicker.last_price)
            .where(
                CryptoTicker.security_id == security_id,
                CryptoTicker.snapshot_time >= day_start,
                CryptoTicker.snapshot_time < day_end,
                CryptoTicker.last_price.isnot(None),
            )
            .order_by(CryptoTicker.snapshot_time.asc())
            .limit(1)
        )
        open_price = session.execute(first_stmt).scalar()

        # Get last snapshot (close price + volume)
        last_stmt = (
            select(CryptoTicker.last_price, CryptoTicker.volume_24h)
            .where(
                CryptoTicker.security_id == security_id,
                CryptoTicker.snapshot_time >= day_start,
                CryptoTicker.snapshot_time < day_end,
                CryptoTicker.last_price.isnot(None),
            )
            .order_by(CryptoTicker.snapshot_time.desc())
            .limit(1)
        )
        last_row = session.execute(last_stmt).first()

        if open_price is None or last_row is None:
            continue

        row = {
            "security_id": security_id,
            "interval": interval,
            "open_time": day_start,
            "open": open_price,
            "high": agg.high,
            "low": agg.low,
            "close": last_row.last_price,
            "volume": last_row.volume_24h,
            "turnover": last_row.volume_24h,
        }

        stmt = insert(CryptoOHLCV).values(row)
        stmt = stmt.on_conflict_do_update(
            constraint="uq_crypto_ohlcv_sec_interval_time",
            set_={
                "open": stmt.excluded.open,
                "high": stmt.excluded.high,
                "low": stmt.excluded.low,
                "close": stmt.excluded.close,
                "volume": stmt.excluded.volume,
                "turnover": stmt.excluded.turnover,
            },
        )
        session.execute(stmt)
        session.flush()
        total_upserted += 1
        logger.debug(f"Upserted daily OHLCV candle for {symbol}")

    logger.info(f"Daily OHLCV generation complete: {total_upserted} rows upserted")
    return total_upserted


def fetch_and_store_global_metrics(session) -> dict:
    """
    Fetch global crypto market metrics from CoinMarketCap
    and the Fear & Greed index from alternative.me, then upsert into
    the CryptoGlobalMetrics table (one row per day).

    Returns a dict summarizing the fetched data.
    """
    result = {}
    today = date.today()

    # ── CMC global metrics ──
    try:
        cmc_data = _cmc.fetch_global_metrics()
        usd_quote = cmc_data.get("quote", {}).get("USD", {})

        result["total_market_cap_usd"] = usd_quote.get("total_market_cap")
        result["total_volume_24h_usd"] = usd_quote.get("total_volume_24h")
        result["btc_dominance_pct"] = cmc_data.get("btc_dominance")
        result["eth_dominance_pct"] = cmc_data.get("eth_dominance")
        result["active_coins"] = cmc_data.get("active_cryptocurrencies")
    except Exception as e:
        logger.error(f"Failed to fetch CMC global metrics: {e}")

    # ── Fear & Greed Index (free public API, no CMC credits) ──
    try:
        with httpx.Client(timeout=10.0) as client:
            resp = client.get(FEAR_GREED_URL, params={"limit": 1})
            resp.raise_for_status()
            fg_data = resp.json().get("data", [])

        if fg_data:
            result["fear_greed_value"] = int(fg_data[0].get("value", 0))
            result["fear_greed_label"] = fg_data[0].get("value_classification", "")
    except Exception as e:
        logger.error(f"Failed to fetch Fear & Greed index: {e}")

    if not result:
        logger.warning("No global metrics fetched; skipping upsert")
        return result

    # ── Upsert into CryptoGlobalMetrics ──
    row = {"date": today}
    if result.get("total_market_cap_usd") is not None:
        row["total_market_cap_usd"] = Decimal(str(result["total_market_cap_usd"]))
    if result.get("total_volume_24h_usd") is not None:
        row["total_volume_24h_usd"] = Decimal(str(result["total_volume_24h_usd"]))
    if result.get("btc_dominance_pct") is not None:
        row["btc_dominance_pct"] = Decimal(str(round(result["btc_dominance_pct"], 2)))
    if result.get("eth_dominance_pct") is not None:
        row["eth_dominance_pct"] = Decimal(str(round(result["eth_dominance_pct"], 2)))
    if result.get("active_coins") is not None:
        row["active_coins"] = result["active_coins"]
    if result.get("fear_greed_value") is not None:
        row["fear_greed_value"] = result["fear_greed_value"]
    if result.get("fear_greed_label") is not None:
        row["fear_greed_label"] = result["fear_greed_label"]

    stmt = insert(CryptoGlobalMetrics).values(row)
    update_cols = {k: v for k, v in row.items() if k != "date"}
    stmt = stmt.on_conflict_do_update(
        index_elements=["date"],
        set_=update_cols,
    )
    session.execute(stmt)
    session.flush()

    logger.info(f"Upserted global crypto metrics for {today}")
    return result


def cleanup_old_tickers(
    session, retention_hours: int = CRYPTO_TICKER_RETENTION_HOURS
) -> int:
    """
    Delete CryptoTicker rows older than `retention_hours`.
    Returns the number of rows deleted.
    """
    cutoff = datetime.now(UTC) - timedelta(hours=retention_hours)
    deleted = (
        session.query(CryptoTicker)
        .filter(CryptoTicker.snapshot_time < cutoff)
        .delete(synchronize_session=False)
    )
    session.flush()
    logger.info(
        f"Deleted {deleted} old crypto ticker snapshots (retention={retention_hours}h)"
    )
    return deleted


def _publish_crypto_update(data: dict) -> None:
    """
    Publish a crypto data update to Redis pub/sub on the
    `tse:live:crypto` channel.
    """
    try:
        from api.cache import cache_manager

        if cache_manager.available:
            cache_manager._client.publish(
                REDIS_CHANNEL_CRYPTO,
                json.dumps(data, default=str),
            )
    except Exception as e:
        logger.debug(f"Redis publish error (crypto): {e}")
