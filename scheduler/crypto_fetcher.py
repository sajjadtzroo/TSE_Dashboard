"""
CoinMarketCap data fetcher for the crypto dashboard.
Fetches real-time listings, global metrics, and Fear & Greed index,
converts USD prices to IRR via CMC's built-in convert parameter,
and stores everything in PostgreSQL.

Daily OHLCV candles are self-generated by aggregating ticker snapshots
(CMC free tier does not include historical OHLCV).
"""

import json
import logging
from datetime import UTC, date, datetime, timedelta
from decimal import Decimal

import httpx
from sqlalchemy import func, select
from sqlalchemy.dialects.postgresql import insert

from config.settings import (
    CMC_API_KEY,
    CMC_BASE_URL,
    CRYPTO_TICKER_RETENTION_HOURS,
)
from database.models import (
    CryptoGlobalMetrics,
    CryptoOHLCV,
    CryptoTicker,
    Security,
)

logger = logging.getLogger(__name__)

# Redis pub/sub channel for live crypto updates
REDIS_CHANNEL_CRYPTO = "tse:live:crypto"

# Fear & Greed API endpoint (free public API, no credits)
FEAR_GREED_URL = "https://api.alternative.me/fng/"


# ---------------------------------------------------------------------------
# CoinMarketCap Client
# ---------------------------------------------------------------------------


class CMCClient:
    """Synchronous HTTP client for the CoinMarketCap Pro API."""

    def __init__(
        self,
        api_key: str = CMC_API_KEY,
        base_url: str = CMC_BASE_URL,
        timeout: float = 15.0,
    ):
        self.base_url = base_url.rstrip("/")
        self.api_key = api_key
        self.timeout = timeout
        self._headers = {
            "X-CMC_PRO_API_KEY": self.api_key,
            "Accept": "application/json",
        }

    def _get(self, path: str, params: dict | None = None) -> dict:
        """Execute a GET request and return the parsed JSON response."""
        url = f"{self.base_url}{path}"
        with httpx.Client(timeout=self.timeout) as client:
            resp = client.get(url, params=params, headers=self._headers)
            resp.raise_for_status()
            data = resp.json()
        status = data.get("status", {})
        if status.get("error_code", 0) != 0:
            raise RuntimeError(
                f"CMC API error on {path}: code={status.get('error_code')}, "
                f"msg={status.get('error_message')}"
            )
        return data.get("data", {})

    def fetch_listings(self, limit: int = 30) -> list[dict]:
        """
        GET /v1/cryptocurrency/listings/latest
        Returns top `limit` cryptocurrencies sorted by market cap,
        with quotes in both USD and IRR.
        """
        params = {
            "limit": limit,
            "convert": "USD",
            "sort": "market_cap",
            "sort_dir": "desc",
        }
        data = self._get("/v1/cryptocurrency/listings/latest", params=params)
        # data is a list of coin objects
        return data if isinstance(data, list) else []

    def fetch_global_metrics(self) -> dict:
        """
        GET /v1/global-metrics/quotes/latest
        Returns global crypto market metrics (total market cap, volume, dominance).
        """
        params = {"convert": "USD"}
        return self._get("/v1/global-metrics/quotes/latest", params=params)


